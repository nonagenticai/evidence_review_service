"""`FND-009`, `13-…:781-783` — the run-manifest builder's one load-bearing rule.

    The full manifest in document `08` is generated by a shared builder. The builder
    refuses to finalize when a capability declares a required field and it is
    absent. Services store the manifest JSON as an immutable artifact and index its
    ID/hash with the owning run/version.

`application/services/run_manifest.build_run_manifest` is that builder. This is a
*unit* file: no database, no fixtures directory, no network. The manifest content
below is written out by hand rather than read from `research_contracts`'
`fixtures/foundation/v1/valid/run-manifest-*.json` on purpose — those files live in
a sibling repo (`/Users/mini3/Movies/knowledge/research_contracts`) that this
service's CI does not check out, so a test depending on them would pass on a dev
machine and fail the moment it runs anywhere else. The shape is the same one those
fixtures use; only the source is inlined.

Four claims, each with its own negative control built in rather than assumed:

1. A manifest carrying every group the released schema requires unconditionally
   (`inputs`, `versions`, `method`, `environment`, `outputs`) finalizes and
   `validate_instance` reports zero errors against it — proving the builder hands
   back an object the released document actually accepts, not merely one it
   believes it built correctly.
2. A capability that declares a field required, and that field is absent, is
   refused — and the refusal names BOTH the capability id and the field pointer,
   in the exception's message and in its structured `missing_capability_fields`
   extra. A test that only checked "an exception was raised" could not tell this
   refusal apart from a bug that refused every manifest unconditionally.
3. The refusal is FALSIFIABLE: the identical manifest, with the identical field
   still absent, finalizes when no capability declared that field required. This
   is the negative control for claim 2 — without it, claim 2 could be passing
   because the builder refuses everything, and this file would not know.
4. The finalized manifest cannot be mutated — at the top level, at a nested
   level, and as an attempt to reassign the dataclass's own field.
"""

