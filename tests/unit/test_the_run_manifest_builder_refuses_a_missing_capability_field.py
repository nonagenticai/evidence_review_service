def test_the_refusal_is_falsifiable_an_undeclared_absent_field_still_finalizes():
    """The negative control for claim 2: same manifest, same absent `rights` group,
    NO capability declares it required. If the builder refused unconditionally —
    "just refuse everything about an absent optional group" — this would also
    raise, and claim 2 would have been trivially true rather than load-bearing.
    """
    fields = _minimal_fields()
    assert "rights" not in fields

    result = build_run_manifest(fields, capability_requirements=())

    assert "rights" not in result.instance
    assert validate_instance(result.instance, RUN_MANIFEST_SCHEMA_REF) == []


def test_a_capability_declaring_a_field_that_is_actually_present_still_finalizes():
    """A requirement the manifest already satisfies is not a refusal — the gate is
    "declared and absent", not "declared" alone."""
    fields = _minimal_fields()

    result = build_run_manifest(
        fields,
        capability_requirements=[CapabilityRequirement(capability_id="markov-audit", field_pointer="/method/seed")],
    )

    assert result.instance["method"]["seed"] == 20260730


