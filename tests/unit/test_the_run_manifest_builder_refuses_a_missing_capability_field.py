def test_a_complete_manifest_finalizes_and_validates_against_the_released_schema_with_zero_errors():
    result = build_run_manifest(_minimal_fields())

    assert isinstance(result, FinalizedRunManifest)
    assert result.instance["schema_ref"] == RUN_MANIFEST_SCHEMA_REF
    assert result.instance["content_hash"] == result.content_hash
    # Placeholder replaced with a real digest, not left behind.
    assert result.content_hash != "sha256:" + "0" * 64

    errors = validate_instance(result.instance, RUN_MANIFEST_SCHEMA_REF)
    assert errors == []


# --------------------------------------------------------------------- claim 2 ---


def test_a_field_a_capability_declared_required_and_that_is_absent_is_refused_naming_both():
    fields = _minimal_fields()
    assert "rights" not in fields  # the field this test relies on being absent

    with pytest.raises(RunManifestRequiredFieldAbsentError) as excinfo:
        build_run_manifest(
            fields,
            capability_requirements=[
                CapabilityRequirement(capability_id="hta-appraisal", field_pointer="/rights/translation_status")
            ],
        )

    error = excinfo.value
    # The capability id and the exact field are both in the human-readable detail...
    assert "hta-appraisal" in error.detail
    assert "/rights/translation_status" in error.detail
    # ...and in the structured extra a caller would actually branch on, so a
    # consumer never has to parse prose to find out what to fix.
    assert error.extra["missing_capability_fields"] == [
        {"capability_id": "hta-appraisal", "field_pointer": "/rights/translation_status"}
    ]
    assert error.missing == (("hta-appraisal", "/rights/translation_status"),)
    assert error.status == 422


def test_two_capabilities_missing_two_different_fields_are_both_named():
    fields = _minimal_fields()

    with pytest.raises(RunManifestRequiredFieldAbsentError) as excinfo:
        build_run_manifest(
            fields,
            capability_requirements=[
                CapabilityRequirement(capability_id="hta-appraisal", field_pointer="/rights"),
                CapabilityRequirement(capability_id="extraction-audit", field_pointer="/extraction"),
            ],
        )

    missing_ids = {entry["capability_id"] for entry in excinfo.value.extra["missing_capability_fields"]}
    missing_pointers = {entry["field_pointer"] for entry in excinfo.value.extra["missing_capability_fields"]}
    assert missing_ids == {"hta-appraisal", "extraction-audit"}
    assert missing_pointers == {"/rights", "/extraction"}


