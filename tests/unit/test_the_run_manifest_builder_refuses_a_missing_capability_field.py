def test_a_finalized_manifest_cannot_be_mutated_at_the_top_level():
    result = build_run_manifest(_minimal_fields())

    with pytest.raises(TypeError):
        result.instance["outputs"] = {}


def test_a_finalized_manifest_cannot_be_mutated_at_a_nested_level():
    result = build_run_manifest(_minimal_fields())

    with pytest.raises(TypeError):
        result.instance["inputs"]["parameters"][0]["value_decimal"] = "9.999"

    with pytest.raises(TypeError):
        result.instance["outputs"]["artifact_refs"].append({})


def test_a_finalized_manifest_dataclass_field_cannot_be_reassigned():
    import dataclasses

    result = build_run_manifest(_minimal_fields())

    with pytest.raises(dataclasses.FrozenInstanceError):
        result.content_hash = "sha256:" + "9" * 64


# ---------------------------------------------------------------------------
# A pointer that cannot be walked is not an absent field.
#
# `field_pointer` is INPUT. The first version raised a bare `ValueError` for a
# pointer not starting with `/`, which escaped the problem-details machinery
# and surfaced as a 500 — the service reporting its own fault for the caller's
# mistake — and it crashed outright on a segment like `\u00b2`, because
# `str.isdigit()` is True for non-ASCII digits while `int()` of one raises.
# Both are now typed 422s or plain absence, and neither can take the process
# down or be mistaken for "the manifest is missing that field".
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("pointer", "because"),
    [
        pytest.param("rights/translation_status", "no leading slash", id="no-leading-slash"),
        pytest.param("", "the empty pointer requires nothing", id="empty"),
        pytest.param("/rights/~2bad", "'~' is only legal as '~0' or '~1'", id="bad-escape"),
    ],
)
def test_a_pointer_that_cannot_express_a_requirement_is_a_typed_422(pointer, because):
    with pytest.raises(RunManifestMalformedPointerError) as excinfo:
        build_run_manifest(
            _minimal_fields(),
            capability_requirements=[CapabilityRequirement(capability_id="hta-appraisal", field_pointer=pointer)],
        )

    error = excinfo.value
    assert error.status == 422, because
    # The capability is named, so an operator knows which declaration to fix
    # rather than which manifest to blame.
    assert error.capability_id == "hta-appraisal"
    assert error.extra["field_pointer"] == pointer


def test_the_empty_pointer_is_refused_rather_than_silently_always_satisfied():
    """RFC 6901 makes `""` the whole document, so it is a VALID pointer and a
    vacuous REQUIREMENT. Walking it would return "present" for every manifest
    that could ever exist, leaving a capability gate that looks enforced and
    enforces nothing."""
    with pytest.raises(RunManifestMalformedPointerError) as excinfo:
        build_run_manifest(
            _minimal_fields(),
            capability_requirements=[CapabilityRequirement(capability_id="hta-appraisal", field_pointer="")],
        )

    assert "requires nothing" in excinfo.value.detail


def test_a_non_ascii_digit_index_reads_as_absent_and_does_not_crash():
    """`"\u00b2".isdigit()` is True but `int("\u00b2")` raises. RFC 6901 admits
    only `0` or `[1-9][0-9]*` as an array index, so this is simply not there."""
    with pytest.raises(RunManifestRequiredFieldAbsentError) as excinfo:
        build_run_manifest(
            _minimal_fields(),
            capability_requirements=[
                CapabilityRequirement(capability_id="hta-appraisal", field_pointer="/inputs/input_refs/\u00b2")
            ],
        )

    assert excinfo.value.status == 422


@pytest.mark.parametrize(
    "segment",
    [
        pytest.param("01", id="leading-zero-is-not-an-rfc6901-index"),
        pytest.param("-", id="one-past-the-end-is-never-present"),
        pytest.param("-1", id="negative-is-not-an-index"),
        pytest.param("999", id="out-of-range"),
    ],
)
def test_an_index_that_is_not_a_member_reads_as_absent(segment):
    with pytest.raises(RunManifestRequiredFieldAbsentError):
        build_run_manifest(
            _minimal_fields(),
            capability_requirements=[
                CapabilityRequirement(capability_id="hta-appraisal", field_pointer=f"/inputs/input_refs/{segment}")
            ],
        )
