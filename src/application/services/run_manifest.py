"""`FND-009` — the shared run-manifest builder.

`13-new-services-shared-implementation-foundation.md:781-783` (section 11.4):

    The full manifest in document `08` is generated by a shared builder. The builder refuses to
    finalize when a capability declares a required field and it is absent. Services store the
    manifest JSON as an immutable artifact and index its ID/hash with the owning run/version.

That is two sentences, and this module is only the first of them — building the
manifest and refusing to finalize it. Storing the finalized JSON as an immutable
artifact and indexing its ID/hash with the owning run/version is the CALLER's job
(an artifact store, `13-…:§11.1`, which does not exist in this service yet — see
`domain/snapshot_manifest.py`'s own module docstring for the identical gap on the
evidence-snapshot side). Nothing here writes to a database or a storage plane.

## The released contract this builds against

`urn:datacompany:run-manifest:1` (`research_contracts` `schemas/manifests/run-manifest.v1.schema.json`,
floored at `research-contracts>=0.9.0` in `pyproject.toml`). Its own `$comment` on
`$defs.manifest_fields` is the second load-bearing quote this module implements:

    Requiredness is IMP-DEC-FND002-017: document 13 section 11.4 makes it
    capability-declared ('The builder refuses to finalize when a capability declares
    a required field and it is absent'), so this schema requires only what every run
    has regardless of method — inputs, versions, method, environment and outputs —
    and leaves the four conditional groups optional for a capability to require.

The schema itself, in other words, is written on the assumption that a builder
exactly like this one exists downstream to enforce capability-declared
requiredness over `sources`, `extraction`, `rights` and `approvals` — the four
groups it deliberately leaves optional. `validate_instance` (below) proves the
assembled manifest against the schema and its released `x-datacompany-cross-field`
rules (notably `a_run_output_is_not_also_its_own_input`); it cannot and does not
know which of those four groups THIS run needed, because that fact does not
live in the schema. It lives in a capability declaration, which is this
module's one required input and the one thing it refuses to invent.

## What this module does NOT invent

* **No capability registry.** Nothing in this repository declares "capability
  X requires field Y" yet — there is no `domain/policies/capability_*.py`, no
  `capabilities` table, nothing under `GET /capabilities` (`13-…:§12.3`) that
  ties a capability id to a set of required manifest fields. Inventing that
  registry here would be asserting a contract nobody has written. So
  `CapabilityRequirement` is INPUT: the caller (a future capability registry,
  a pack's capability descriptor, or a test standing in for one) supplies the
  exact `(capability_id, field_pointer)` pairs this run's declared
  capabilities require, and the builder enforces them. It owns none of them.
* **No SLO, retention or residency fields.** `14-…:917` (section 14.2): "Phase
  0 supplies numerical targets. Before then, code and dashboards support but
  do not invent targets…". `13-…:787-793` (section 11.5) gates residency
  policy content on `IMP-DEC-019`, which is open. The released schema carries
  neither, and this builder adds nothing the schema does not already declare
  — see `_FORBIDDEN_CALLER_FIELDS` for the two members it computes itself and
  refuses to accept from a caller (`schema_ref`, `content_hash`); every other
  member is the released document's own vocabulary, verbatim.

## Two refusals, and why they are different exceptions

`RunManifestRequiredFieldAbsentError` is the load-bearing one: a capability this run
declared needed a field this run does not have. It names the exact capability
id and the exact field pointer, in the exception's `detail` string AND in its
structured `missing_capability_fields` extra — never a bare boolean, because
"the manifest builder refused" tells nobody what to fix and "capability
`hta-appraisal` declares `/rights/translation_status` required and it is
absent" does.

`ValidationFailedError` is the generic schema/cross-field gate every released
document gets. It exists so this module can never hand back an object
`urn:datacompany:run-manifest:1` itself rejects — but it is not the interesting
refusal, because the schema's four conditional groups being ABSENT is valid by
the schema's own design (that is the whole point of leaving them optional).
Only a capability declaration turns that absence into a refusal.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from typing import Any

from research_contracts.canonical import validate_instance

from api.problem_details import ProblemError, ValidationFailedError

#: The released document this builder assembles and seals every manifest against.
RUN_MANIFEST_SCHEMA_REF = "urn:datacompany:run-manifest:1"

#: This service's own manifest instances all name the same identity type — the
#: `canonical_type_token` a run manifest names itself, exactly as the released
#: fixtures do (`research_contracts/fixtures/foundation/v1/valid/run-manifest-*.json`
#: both set `"entity_type": "run_manifest"`). Computed, not a caller choice, for
#: the same reason `schema_ref` is: there is exactly one correct value and a
#: caller-supplied one could only ever be that value or a bug.
RUN_MANIFEST_ENTITY_TYPE = "run_manifest"

#: A well-formed placeholder. `urn:datacompany:stable-identity:1#/$defs/content_hash`
#: REQUIRES the field and `compute_content_hash` validates before it hashes, so a
#: manifest cannot be hashed until it already carries one. The released hash
#: profile then excludes the manifest's own `content_hash` from its own hash view
#: (`x-datacompany-hash-excluded`, reason `own_content_hash`), so the placeholder can
#: never reach the digest. Mirrors `domain/snapshot_manifest._HASH_PLACEHOLDER`
#: exactly — same shape, same reason, independently declared because this module
#: does not import from that one (a different released contract, a different
#: bounded bit of the estate; see the module docstring on why they diverge).
_HASH_PLACEHOLDER = "sha256:" + "0" * 64

#: Members the builder computes itself and therefore refuses from a caller.
#: `schema_ref` and `entity_type` because there is exactly one correct value
#: for each of them here (this schema, `RUN_MANIFEST_ENTITY_TYPE`); `content_hash`
#: because a hand-set hash is the one field whose wrongness is invisible until a
#: consumer recomputes it — `domain/snapshot_manifest.seal` makes the identical
#: argument for the evidence-snapshot manifest.
_FORBIDDEN_CALLER_FIELDS = frozenset({"schema_ref", "content_hash", "entity_type"})

#: The five groups `urn:datacompany:run-manifest:1#/$defs/manifest_fields` requires
#: unconditionally — "what every run has regardless of method" per the schema's
#: own `$comment`. Not enforced here (the schema already enforces it via
#: `validate_instance`); named only so a reader of this module can see the
#: complement of `_CAPABILITY_DECLARABLE_GROUPS` without re-opening the schema.
_UNCONDITIONAL_REQUIRED_GROUPS = frozenset({"inputs", "versions", "method", "environment", "outputs"})

#: The four groups the released schema deliberately leaves optional "for a
#: capability to require" (schema `$comment`, quoted in the module docstring).
#: `CapabilityRequirement.field_pointer` is not restricted to these — a
#: capability could in principle name a field inside one of the five
#: unconditional groups too (e.g. a capability that requires `method.seed` be
#: present even though the schema itself does not) — but these four are the
#: groups whose ABSENCE is otherwise silent, which is the case this builder
#: exists for.
_CAPABILITY_DECLARABLE_GROUPS = frozenset({"sources", "extraction", "rights", "approvals"})


@dataclass(frozen=True, slots=True)
class CapabilityRequirement:
    """One capability's declared requirement that a field be present.

    This is INPUT to `build_run_manifest`, never something the builder invents
    — see the module docstring's "What this module does NOT invent". `capability_id`
    is whatever this run's declared/enabled capabilities are identified by
    upstream (`13-…:§12.1`'s "capability IDs"); `field_pointer` is an RFC 6901
    JSON pointer into the ASSEMBLED manifest instance, e.g. `/rights` (the whole
    group), `/rights/translation_status` (one member of it), or
    `/approvals/approval_refs`.

    Two requirements sharing a `capability_id` is how one capability declares
    more than one required field — there is no list-valued form, so that the
    refusal always names one capability and one field per violation rather
    than a capability and an opaque bag of them.
    """

    capability_id: str
    field_pointer: str


class RunManifestMalformedPointerError(ProblemError):
    """A `CapabilityRequirement.field_pointer` that is not a usable RFC 6901 pointer.

    `field_pointer` is INPUT (see `CapabilityRequirement`), so a malformed one is
    the caller's mistake and belongs in the same typed-4xx machinery as every
    other bad input. The first version raised a bare `ValueError` for a pointer
    not starting with `/`, which escaped the problem-details layer entirely and
    surfaced as a 500 — the service reporting its own fault for the caller's.

    It also refuses the EMPTY pointer, which RFC 6901 defines as the whole
    document. That is a valid pointer and a meaningless REQUIREMENT: "this run
    manifest must contain the run manifest" is satisfied by every instance that
    could ever be built, so a capability declaring it would be silently
    unenforceable rather than refused.
    """

    status = 422
    slug = "run_manifest_malformed_pointer"
    title = "Run Manifest Malformed Pointer"

    def __init__(self, capability_id: str, field_pointer: str, reason: str) -> None:
        super().__init__(
            f"capability {capability_id!r} declares field_pointer {field_pointer!r}, which is not a "
            f"usable RFC 6901 JSON pointer into a run manifest: {reason}. The requirement was not "
            "evaluated — a pointer that cannot be walked is a requirement that cannot be checked, "
            "and treating it as satisfied would make the capability gate silently vacuous.",
            capability_id=capability_id,
            field_pointer=field_pointer,
        )
        self.capability_id = capability_id
        self.field_pointer = field_pointer


class RunManifestRequiredFieldAbsentError(ProblemError):
    """`13-…:781-783` — "The builder refuses to finalize when a capability
    declares a required field and it is absent." This IS that refusal.

    Never raised bare: `missing` names every `(capability_id, field_pointer)`
    pair this manifest failed, both in `detail` (for a human) and in the
    `missing_capability_fields` extra (for a caller that wants to act on it
    without parsing prose) — see the module docstring's "Two refusals" section
    for why a boolean or a generic 422 would not do.
    """

    status = 422
    slug = "run_manifest_required_field_absent"
    title = "Run Manifest Required Field Absent"

    def __init__(self, missing: Sequence[tuple[str, str]]) -> None:
        if not missing:  # pragma: no cover - defensive; callers only construct this with failures
            raise ValueError("RunManifestRequiredFieldAbsentError requires at least one missing (capability, field)")
        rendered = "; ".join(
            f"capability {capability_id!r} declares {field_pointer!r} required"
            for capability_id, field_pointer in missing
        )
        detail = (
            f"{len(missing)} declared capability requirement(s) are absent from this run manifest, "
            f"so it cannot finalize: {rendered}. A manifest that finalized anyway would lie about "
            "the run it describes."
        )
        super().__init__(
            detail,
            missing_capability_fields=[
                {"capability_id": capability_id, "field_pointer": field_pointer}
                for capability_id, field_pointer in missing
            ],
        )
        self.missing = tuple(missing)


class _FrozenDict(dict):
    """A `dict` subclass that reads exactly like a `dict` and mutates like nothing.

    Immutability here cannot be `types.MappingProxyType`: `research_contracts`'
    schema validation is plain `jsonschema`, whose default type checker tests
    `isinstance(instance, dict)` for the `"object"` keyword — a `MappingProxyType`
    (or any non-`dict` `Mapping`) fails that check with `"is not of type 'object'"`
    before a single property is even looked at. Measured while building this
    module: freezing the sealed instance with `MappingProxyType`/`tuple` made
    `validate_instance` on the FINALIZED manifest report nothing but "not of type
    'object'"/"'array'" — the opposite of the zero-errors promise this builder
    makes. A `dict`/`list` subclass that only overrides the WRITE methods keeps
    `isinstance` (and every read path `jsonschema` and a consumer take) true,
    while every write raises.

    ⚠️ `__init__` IS ONE OF THE WRITE METHODS, and the first version of this
    class did not treat it as one. `dict.__init__` does not construct — it
    UPDATES IN PLACE — so an already-sealed instance could be re-seeded through
    it: `finalized.instance.__init__({"entity_type": "FORGED"})` rewrote the
    manifest while `finalized.content_hash` went on certifying the content it
    used to hold. Overriding the thirteen obvious mutators and leaving the
    initialiser open is not a freeze; it is a freeze with a documented bypass.
    So `__init__` refuses like every other write, and construction goes through
    `_seal()`, which populates the object via the BASE-class method without
    ever routing through the overrides.
    """

    __slots__ = ()

    @classmethod
    def _seal(cls, mapping: Mapping[str, Any]) -> _FrozenDict:
        """Build a populated, already-frozen instance.

        `dict.__new__` does not call `__init__`, and `dict.update(obj, ...)` is
        the unbound base method, so neither passes through the refusals below.
        """
        obj = dict.__new__(cls)
        dict.update(obj, mapping)
        return obj

    def _read_only(self, *_args: Any, **_kwargs: Any) -> Any:
        raise TypeError("a finalized run manifest cannot be mutated")

    __init__ = _read_only
    __setitem__ = _read_only
    __delitem__ = _read_only
    __ior__ = _read_only
    clear = _read_only
    pop = _read_only
    popitem = _read_only
    setdefault = _read_only
    update = _read_only


class _FrozenList(list):
    """`list`'s read path (`isinstance`, indexing, iteration, length) with every write refused.

    See `_FrozenDict` for why a `tuple` cannot stand in here: `jsonschema`'s
    `"array"` type check is `isinstance(instance, list)`, which a `tuple` fails.
    See it also for why `__init__` is refused rather than relied on for
    construction — `list.__init__` re-seeds in place exactly as `dict`'s does.
    """

    __slots__ = ()

    @classmethod
    def _seal(cls, items: Iterable[Any]) -> _FrozenList:
        """Build a populated, already-frozen instance. See `_FrozenDict._seal`."""
        obj = list.__new__(cls)
        list.extend(obj, items)
        return obj

    def _read_only(self, *_args: Any, **_kwargs: Any) -> Any:
        raise TypeError("a finalized run manifest cannot be mutated")

    __init__ = _read_only
    __setitem__ = _read_only
    __delitem__ = _read_only
    __iadd__ = _read_only
    __imul__ = _read_only
    append = _read_only
    extend = _read_only
    insert = _read_only
    remove = _read_only
    pop = _read_only
    clear = _read_only
    sort = _read_only
    reverse = _read_only


@dataclass(frozen=True, slots=True)
class FinalizedRunManifest:
    """A sealed, immutable `urn:datacompany:run-manifest:1` instance.

    `instance` is a recursively frozen view (`_FrozenDict` over every mapping,
    `_FrozenList` over every list) of the manifest exactly as it validates
    against the released schema — including its real `content_hash`, which is
    `content_hash` on this dataclass too, spelled twice for the same reason
    `EvidenceSnapshot` and its sealed manifest both carry one: a caller that
    only has the dataclass should not have to walk into `instance` to learn
    what it is keyed by.

    The dataclass is frozen and `instance` is read-only end to end, so neither
    `result.content_hash = ...` nor `result.instance["outputs"] = ...` nor
    mutating a nested member succeeds — finalizing is the last write. And
    because the freeze uses `dict`/`list` subclasses rather than
    `MappingProxyType`/`tuple`, `validate_instance(result.instance, ...)` still
    sees an "object" and an "array" exactly where the released schema expects
    them — the immutability is invisible to every reader, including the schema
    validator, and refuses only a write.
    """

    instance: Mapping[str, Any]
    content_hash: str


def _validate_pointer(capability_id: str, pointer: str) -> None:
    """Refuse a `field_pointer` that cannot express a requirement. See
    `RunManifestMalformedPointerError` for why each case is refused rather than
    read as absence — absence is a fact about the MANIFEST, and these are facts
    about the POINTER."""
    if pointer == "":
        raise RunManifestMalformedPointerError(
            capability_id, pointer, "the empty pointer names the whole document, so it requires nothing"
        )
    if not pointer.startswith("/"):
        raise RunManifestMalformedPointerError(capability_id, pointer, "an RFC 6901 pointer must start with '/'")
    for raw_segment in pointer.split("/")[1:]:
        stripped = raw_segment.replace("~0", "").replace("~1", "")
        if "~" in stripped:
            raise RunManifestMalformedPointerError(
                capability_id,
                pointer,
                "'~' is an RFC 6901 escape and is only legal as '~0' (a literal '~') or '~1' (a literal '/')",
            )


def _resolve_pointer(instance: Any, pointer: str) -> tuple[bool, Any]:
    """Walk an RFC 6901 JSON pointer over `instance`. Returns `(present, value)`.

    Absence anywhere along the path — a missing key, an out-of-range or
    non-integer array index, or stepping into a non-container — counts as
    absence of the WHOLE pointer. That is deliberate: a capability that
    requires `/rights/translation_status` is refused identically whether
    `rights` itself is missing or `rights` is present but its
    `translation_status` member is not — both mean the run does not carry
    what the capability declared it needed.

    `pointer` MUST already have been accepted by `_validate_pointer` — this
    function walks, it does not validate, and it is never reached with an empty
    or `/`-less pointer.
    """
    node: Any = instance
    for raw_segment in pointer.split("/")[1:]:
        segment = raw_segment.replace("~1", "/").replace("~0", "~")
        if isinstance(node, Mapping):
            if segment not in node:
                return False, None
            node = node[segment]
        elif isinstance(node, (list, tuple)):
            # ⚠️ `str.isdigit()` is TRUE for non-ASCII digit characters —
            # `"\u00b2".isdigit()` (superscript two) is True and `int()` of it
            # raises `ValueError`. The first version used `.isdigit()` alone and
            # crashed on such a segment instead of reporting absence. RFC 6901
            # §4 admits only `0` or `[1-9][0-9]*` as an array index, so anything
            # else — a non-ASCII digit, a leading zero, a sign, or `-` (the
            # "one past the last element" token, which is never present) — is
            # simply not there.
            if not (segment.isascii() and segment.isdigit()):
                return False, None
            if len(segment) > 1 and segment[0] == "0":
                return False, None
            index = int(segment)
            if index >= len(node):
                return False, None
            node = node[index]
        else:
            return False, None
    return True, node


def _missing_capability_fields(
    instance: Mapping[str, Any], requirements: Sequence[CapabilityRequirement]
) -> list[tuple[str, str]]:
    """Every `(capability_id, field_pointer)` this instance fails, in declared order.

    Order preserved (not deduplicated, not sorted) so the refusal reads in the
    order the caller declared its capabilities, and so two capabilities that
    both require the same absent field are both named — a capability audit
    should not have one of its violations silently swallowed because another
    capability already reported the same gap.
    """
    missing: list[tuple[str, str]] = []
    for requirement in requirements:
        _validate_pointer(requirement.capability_id, requirement.field_pointer)
        present, _ = _resolve_pointer(instance, requirement.field_pointer)
        if not present:
            missing.append((requirement.capability_id, requirement.field_pointer))
    return missing


def _freeze(value: Any) -> Any:
    """Recursively freeze `value` into `_FrozenDict`/`_FrozenList`, leaving scalars alone.

    Depth matters — freezing only the top level would let a caller mutate a
    nested list or dict (e.g. `instance["outputs"]["artifact_refs"]`) and the
    "finalized manifest cannot be mutated" promise would be true only one
    level down.
    """
    if isinstance(value, Mapping):
        return _FrozenDict._seal({key: _freeze(item) for key, item in value.items()})
    if isinstance(value, list):
        return _FrozenList._seal(_freeze(item) for item in value)
    return value


def build_run_manifest(
    fields: Mapping[str, Any],
    *,
    capability_requirements: Sequence[CapabilityRequirement] = (),
) -> FinalizedRunManifest:
    """Assemble, capability-check, hash and freeze one `urn:datacompany:run-manifest:1` instance.

    `fields` is the caller's already-resolved manifest content — every member
    of the released document this run has, EXCEPT `schema_ref`, `entity_type`
    and `content_hash`, which this function supplies itself (see
    `_FORBIDDEN_CALLER_FIELDS`) and refuses if the caller also supplies them,
    rather than silently overwriting a caller value that might disagree.

    Refusal order, and why it is this order:

    1. **Forbidden caller fields** (`ValidationFailedError`) — a caller error
       about how the builder is being called, not about the run.
    2. **Capability-declared fields absent** (`RunManifestRequiredFieldAbsentError`)
       — `13-…:781-783`'s load-bearing rule, checked before general schema
       validation because it is the more actionable diagnosis: a missing
       `/rights/translation_status` is "this run needed rights status and
       doesn't have it", not merely "this object fails the schema" (it does
       not fail the schema at all — `rights` is optional there).
    3. **Released schema and cross-field rules** (`ValidationFailedError`,
       via `validate_instance`) — the general gate every released document
       gets, run BOTH before and after sealing: before, so a caller error
       (e.g. a malformed `run_ref`) is reported before any hash is computed
       over it; after, so the exact object this function hands back — the one
       with its REAL `content_hash` rather than the placeholder — is proven to
       satisfy the released document with zero errors, which is `validate_instance`'s
       own return contract (an empty list) and this function's own promise.

    Returns a `FinalizedRunManifest` whose `instance` cannot be mutated — see
    that dataclass's docstring.
    """
    forbidden = _FORBIDDEN_CALLER_FIELDS & fields.keys()
    if forbidden:
        raise ValidationFailedError(
            f"run manifest field(s) {sorted(forbidden)} are computed by the builder and must not "
            "be supplied by the caller"
        )

    instance: dict[str, Any] = {
        **fields,
        "entity_type": RUN_MANIFEST_ENTITY_TYPE,
        "schema_ref": RUN_MANIFEST_SCHEMA_REF,
        "content_hash": _HASH_PLACEHOLDER,
    }

    missing = _missing_capability_fields(instance, capability_requirements)
    if missing:
        raise RunManifestRequiredFieldAbsentError(missing)

    pre_seal_errors = validate_instance(instance, RUN_MANIFEST_SCHEMA_REF)
    if pre_seal_errors:
        raise ValidationFailedError(
            f"run manifest does not satisfy {RUN_MANIFEST_SCHEMA_REF}: " + "; ".join(pre_seal_errors)
        )

    from research_contracts.canonical.engine import compute_content_hash

    content_hash = compute_content_hash(instance, RUN_MANIFEST_SCHEMA_REF)
    sealed: dict[str, Any] = {**instance, "content_hash": content_hash}

    # The object this function actually hands back, proven against the released
    # document ONE MORE TIME rather than trusted from `compute_content_hash`'s
    # own internal validation (which ran against the PLACEHOLDER-hashed
    # instance, not this one). `validate_instance`'s contract is "zero errors
    # means valid"; a caller of THIS function gets to rely on that having been
    # checked on the exact bytes it receives.
    post_seal_errors = validate_instance(sealed, RUN_MANIFEST_SCHEMA_REF)
    if post_seal_errors:  # pragma: no cover - would mean compute_content_hash produced an invalid hash
        raise ValidationFailedError(
            f"sealed run manifest does not satisfy {RUN_MANIFEST_SCHEMA_REF}: " + "; ".join(post_seal_errors)
        )

    return FinalizedRunManifest(instance=_freeze(sealed), content_hash=content_hash)
